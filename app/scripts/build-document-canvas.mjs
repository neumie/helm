import { writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

/** The exact production worker bundle; never evaluates a document or traverses its imports. */
export async function buildDocumentCanvas() {
	const result = await build({
		entryPoints: [fileURLToPath(new URL('../src/renderer/document-review/canvas-worker.ts', import.meta.url))],
		bundle: true,
		write: false,
		platform: 'browser',
		format: 'iife',
		globalName: 'HelmReviewCanvasWorker',
		target: 'es2022',
		minify: true,
		define: { 'process.env.NODE_ENV': '"production"' },
	})
	const source = result.outputFiles[0].text
	await writeFile(
		new URL('../src/renderer/document-review/canvas-runtime.generated.ts', import.meta.url),
		`// Generated by build-document-canvas.mjs; do not edit.\nexport const reviewCanvasWorkerSource: string = ${JSON.stringify(source)}\n`,
	)
	return source
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await buildDocumentCanvas()
